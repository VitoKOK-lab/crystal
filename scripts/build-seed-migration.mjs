// Generates migrations/0002_seed.sql from the catalog that currently lives
// in code (app/catalog.tsx + app/series.ts), so the D1 database starts with
// exactly the 21 stones / 37 accessories / 8 series / 32 products the site
// ships today — the owner never re-enters anything.
//
// Run manually when catalog code changes BEFORE the admin backend exists:
//     node scripts/build-seed-migration.mjs
// Once the admin backend is live, the database is the source of truth and
// this script is retired.
import { writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { importCompiled } from "../tests/esbuild-import.mjs";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const catalog = await importCompiled(path.join(ROOT, "app/catalog.tsx"));
const seriesMod = await importCompiled(path.join(ROOT, "app/series.ts"));

const q = (v) => `'${String(v).replaceAll("'", "''")}'`;
const lines = [
  "-- AUTO-GENERATED by scripts/build-seed-migration.mjs — do not hand-edit.",
  "-- Seeds D1 with the catalog the static site shipped with. Stock starts",
  "-- at 99 everywhere so nothing shows 補貨中 before the owner sets real",
  "-- counts in the admin backend (Phase 2).",
];

const DEFAULT_STOCK = 99;
// Reproduces the studio's current fixed size ladder (catalog BEAD_MM +
// itemPrice deltas). Becomes per-stone editable data from day one.
const SIZE_LADDER = [
  { mm: 8, delta: 0 },
  { mm: 10, delta: 80 },
  { mm: 20, delta: 320 },
];

catalog.stones.forEach((s, i) => {
  const photo = catalog.stonePhotos[s.id];
  if (!photo) throw new Error(`stone ${s.id} has no photo`);
  lines.push(`INSERT INTO stones (id, zh, en, energy_zh, price, note, energies, photo, sort) VALUES (${q(s.id)}, ${q(s.zh)}, ${q(s.en)}, ${q(s.group)}, ${s.price}, ${q(s.note)}, ${q(JSON.stringify(s.energy))}, ${q(photo)}, ${i});`);
  for (const { mm, delta } of SIZE_LADDER) {
    lines.push(`INSERT INTO stone_sizes (stone_id, mm, price_delta, stock) VALUES (${q(s.id)}, ${mm}, ${delta}, ${DEFAULT_STOCK});`);
  }
});

catalog.accessories.forEach((a, i) => {
  const photo = catalog.accessoryPhotos[a.id];
  if (!photo) throw new Error(`accessory ${a.id} has no photo`);
  lines.push(`INSERT INTO accessories (id, zh, en, type, metal, price, note, photo, stock, sort) VALUES (${q(a.id)}, ${q(a.zh)}, ${q(a.en)}, ${q(a.type)}, ${q(a.metal)}, ${a.price}, ${q(a.note)}, ${q(photo)}, ${DEFAULT_STOCK}, ${i});`);
});

seriesMod.SERIES.forEach((s, i) => {
  const { products, ...tone } = s;
  lines.push(`INSERT INTO series (id, name, en, tone, sort) VALUES (${q(s.id)}, ${q(s.zh)}, ${q(s.en)}, ${q(JSON.stringify(tone))}, ${i});`);
  products.forEach((p, j) => {
    lines.push(`INSERT INTO products (id, series_id, name, tagline, style, wrist, spec, sort) VALUES (${q(p.id)}, ${q(s.id)}, ${q(p.name)}, ${q(p.tagline)}, ${q(p.style)}, ${p.wrist}, ${q(p.spec)}, ${j});`);
  });
});

const out = path.join(ROOT, "migrations/0002_seed.sql");
writeFileSync(out, lines.join("\n") + "\n");
const counts = `stones=${catalog.stones.length} accessories=${catalog.accessories.length} series=${seriesMod.SERIES.length} products=${seriesMod.SERIES.reduce((n, s) => n + s.products.length, 0)}`;
console.log(`wrote ${out} (${counts})`);
if (catalog.stones.length !== 21 || catalog.accessories.length !== 37) {
  throw new Error(`unexpected catalog counts: ${counts}`);
}
